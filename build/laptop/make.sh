#!/usr/bin/env bash
# lolssd laptop: autounattend.xml for a stock Windows 11 installer — tiny11 next to Linux on the
# same disk. The file goes into the root of the installer (FAT32 disk from winsetup-disk.sh);
# setup then asks only for the edition/key and the disk (pick the unallocated space).
#   build/laptop/make.sh [user, default $USER]      → dist/laptop/: autounattend.xml, lolssd/wallpaper
# Both go into the installer's root; tiny.ps1 takes the K/DA wallpaper from there.
#   TEST=1 …   also: language, Pro generic key, wipe disk 0 — for the QEMU test only.
# tiny.ps1 rides inside the answer file (Extensions) and runs in the specialize pass.
set -euo pipefail

repo=$(cd "$(dirname "$0")/../.." && pwd)
user=${1:-$USER}
out=$repo/dist/laptop
mkdir -p "$out"
# Wallpaper: K/DA FIRESTARTER splash art (Riot's art, so only in the assets release), cut to
# the stock file names: img0 (desktop), img0_WxH (4K folder, picked by resolution), img100 (lock).
wall=$out/lolssd/wallpaper
pic=$out/kda-firestarter-4k.jpg
mkdir -p "$wall"
if [[ ! -f $wall/img100.jpg ]]; then
	echo "обои K/DA…"
	[[ -s $pic ]] || curl -fsSL --retry 3 -o "$pic" https://github.com/TumaAlex7/lolssd/releases/download/assets/kda-firestarter-4k.jpg
	magick "$pic" -filter Lanczos -resize 3840x2160^ -gravity center -extent 3840x2160 -quality 92 "$wall/img0.jpg"
	for size in 1920x1080 1920x1200 2560x1440 2560x1600 3840x2160; do
		magick "$pic" -filter Lanczos -resize "$size^" -gravity center -extent "$size" -quality 92 "$wall/img0_$size.jpg"
	done
	cp "$wall/img0.jpg" "$wall/img100.jpg"
	rm -f "$pic"
fi

esc() { sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g' "$@"; }

pe_test= key_test=
if [[ -n ${TEST:-} ]]; then
	pe_test='
    <component name="Microsoft-Windows-International-Core-WinPE" processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">
      <SetupUILanguage><UILanguage>en-US</UILanguage></SetupUILanguage>
      <InputLocale>en-US</InputLocale><SystemLocale>en-US</SystemLocale><UILanguage>en-US</UILanguage><UserLocale>en-US</UserLocale>
    </component>'
	key_test='
      <ImageInstall><OSImage><InstallTo><DiskID>0</DiskID><PartitionID>3</PartitionID></InstallTo></OSImage></ImageInstall>
      <DiskConfiguration><Disk wcm:action="add"><DiskID>0</DiskID><WillWipeDisk>true</WillWipeDisk><CreatePartitions>
        <CreatePartition wcm:action="add"><Order>1</Order><Type>EFI</Type><Size>300</Size></CreatePartition>
        <CreatePartition wcm:action="add"><Order>2</Order><Type>MSR</Type><Size>16</Size></CreatePartition>
        <CreatePartition wcm:action="add"><Order>3</Order><Type>Primary</Type><Extend>true</Extend></CreatePartition>
      </CreatePartitions><ModifyPartitions>
        <ModifyPartition wcm:action="add"><Order>1</Order><PartitionID>1</PartitionID><Format>FAT32</Format></ModifyPartition>
        <ModifyPartition wcm:action="add"><Order>2</Order><PartitionID>3</PartitionID><Format>NTFS</Format></ModifyPartition>
      </ModifyPartitions></Disk></DiskConfiguration>'
	key_test=$key_test'
      <UserData><AcceptEula>true</AcceptEula><ProductKey><Key>VK7JG-NPHTM-C97JM-9MPGT-3V66T</Key></ProductKey></UserData>'
else
	key_test='
      <UserData><AcceptEula>true</AcceptEula></UserData>'
fi

cat >"$out/autounattend.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- lolssd laptop: tiny11 on a stock install next to Linux. Generated by build/laptop/make.sh. -->
<unattend xmlns="urn:schemas-microsoft-com:unattend" xmlns:wcm="http://schemas.microsoft.com/WMIConfig/2002/State">
  <settings pass="windowsPE">$pe_test
    <component name="Microsoft-Windows-Setup" processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">
      <RunSynchronous>
        <RunSynchronousCommand wcm:action="add"><Order>1</Order><Path>reg add HKLM\SYSTEM\Setup\LabConfig /v BypassTPMCheck /t REG_DWORD /d 1 /f</Path></RunSynchronousCommand>
        <RunSynchronousCommand wcm:action="add"><Order>2</Order><Path>reg add HKLM\SYSTEM\Setup\LabConfig /v BypassSecureBootCheck /t REG_DWORD /d 1 /f</Path></RunSynchronousCommand>
      </RunSynchronous>$key_test
    </component>
  </settings>
  <settings pass="specialize">
    <component name="Microsoft-Windows-Deployment" processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">
      <RunSynchronous>
        <RunSynchronousCommand wcm:action="add">
          <Order>1</Order>
          <Path>powershell.exe -NoProfile -Command "\$x=[xml]::new();\$x.Load('C:\Windows\Panther\unattend.xml');\$x.unattend.Extensions.File|%{md (Split-Path \$_.path) -Force|Out-Null;Set-Content -LiteralPath \$_.path -Value \$_.InnerText}"</Path>
          <Description>lolssd: extract tiny.ps1 from this file</Description>
        </RunSynchronousCommand>
        <RunSynchronousCommand wcm:action="add">
          <Order>2</Order>
          <Path>powershell.exe -NoProfile -ExecutionPolicy Bypass -File C:\Windows\Setup\Scripts\lolssd-tiny.ps1</Path>
          <Description>lolssd: tiny11 (log: C:\Windows\Setup\Scripts\lolssd-tiny.log)</Description>
        </RunSynchronousCommand>
      </RunSynchronous>
    </component>
  </settings>
  <settings pass="oobeSystem">
    <component name="Microsoft-Windows-International-Core" processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">
      <InputLocale>en-US;ru-RU</InputLocale>
      <SystemLocale>en-US</SystemLocale>
      <UILanguage>en-US</UILanguage>
      <UserLocale>ru-RU</UserLocale>
    </component>
    <component name="Microsoft-Windows-Shell-Setup" processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">
      <OOBE>
        <HideEULAPage>true</HideEULAPage>
        <HideOnlineAccountScreens>true</HideOnlineAccountScreens>
        <HideWirelessSetupInOOBE>true</HideWirelessSetupInOOBE>
        <ProtectYourPC>3</ProtectYourPC>
      </OOBE>
      <UserAccounts>
        <LocalAccounts>
          <LocalAccount wcm:action="add">
            <Name>$user</Name>
            <Group>Administrators</Group>
            <Password><Value></Value><PlainText>true</PlainText></Password>
          </LocalAccount>
        </LocalAccounts>
      </UserAccounts>
      <FirstLogonCommands>
        <SynchronousCommand wcm:action="add">
          <Order>1</Order>
          <CommandLine>powershell.exe -NoProfile -ExecutionPolicy Bypass -File C:\Windows\Setup\Scripts\lolssd-tiny.ps1 -Boot</CommandLine>
          <Description>lolssd: Linux stays the default boot (after setup's last reboot)</Description>
        </SynchronousCommand>
      </FirstLogonCommands>
    </component>
  </settings>
  <Extensions xmlns="urn:lolssd:laptop">
    <File path="C:\Windows\Setup\Scripts\lolssd-tiny.ps1">
$(esc "$repo/build/laptop/tiny.ps1")
    </File>
  </Extensions>
</unattend>
EOF
xmllint --noout "$out/autounattend.xml" 2>/dev/null || python3 -I -c 'import sys,xml.dom.minidom as m; m.parse(sys.argv[1])' "$out/autounattend.xml"
echo "$out/autounattend.xml (пользователь $user, без пароля)"
